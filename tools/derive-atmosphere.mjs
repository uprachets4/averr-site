/**
 * WebP derivatives for the atmosphere images.
 *
 * The sources are owner-generated (Midjourney, paid plan) and already
 * sit in the site's palette, so the grade is LIGHT by instruction: the
 * black point is lifted to the site navy so the images sit on the same
 * ground as everything else, saturation comes down a touch, and the
 * site's film grain goes over the top. No duotone — a heavy two-colour
 * map flattens the mist, which is the one thing these are here for.
 *
 * Nothing is ever upscaled: a 1648px source emits 960/1440/1648, not
 * 1920. Outputs are committed; the sources are gitignored because they
 * are ~60MB of PNG and only the derivatives ship.
 *
 * Re-run with `node tools/derive-atmosphere.mjs`. Idempotent.
 */
import { readdir, writeFile, mkdir, stat } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC = path.join(ROOT, "assets-src/atmosphere");
const OUT = path.join(ROOT, "public/atmos");
const WIDTHS = [960, 1440, 1920, 2560];
const QUALITY = 76;

/** The site navy as the new black point: out = in * m + o per channel. */
const NAVY = [18, 28, 39];
const MUL = NAVY.map((c) => (255 - c) / 255);
const OFF = NAVY;

/** One grain tile, reused for every image. */
async function grain(w, h) {
  const px = Buffer.alloc(w * h);
  let seed = 17;
  for (let i = 0; i < px.length; i++) {
    seed = (seed * 1103515245 + 12345) % 2147483648;
    px[i] = 118 + ((seed >> 7) % 20);
  }
  return sharp(px, { raw: { width: w, height: h, channels: 1 } })
    .toColourspace("b-w")
    .png()
    .toBuffer();
}

await mkdir(OUT, { recursive: true });
const files = (await readdir(SRC)).filter((f) => /\.png$/i.test(f)).sort();
const manifest = {};
let written = 0, skipped = 0, bytes = 0;

for (const name of files) {
  const file = path.join(SRC, name);
  const base = name.replace(/\.png$/i, "");
  const meta = await sharp(file).metadata();
  const widths = WIDTHS.filter((w) => w < meta.width).concat(
    WIDTHS.some((w) => w >= meta.width) ? [meta.width] : []
  );
  const srcStat = await stat(file);
  const g = await grain(Math.ceil(meta.width / 2), Math.ceil(meta.height / 2));

  for (const w of widths) {
    const dest = path.join(OUT, `${base}-${w}.webp`);
    if (existsSync(dest) && (await stat(dest)).mtimeMs > srcStat.mtimeMs) {
      skipped++;
      continue;
    }
    const buf = await sharp(file)
      .resize({ width: w, withoutEnlargement: true })
      .modulate({ saturation: 0.88 })
      .linear(MUL, OFF)
      .composite([
        { input: await sharp(g).resize({ width: w }).toBuffer(), blend: "soft-light" },
      ])
      .webp({ quality: QUALITY })
      .toBuffer();
    await writeFile(dest, buf);
    bytes += buf.length;
    written++;
  }
  manifest[base] = { w: meta.width, h: meta.height, widths };
}

await writeFile(
  path.join(ROOT, "src/data/atmosphere.ts"),
  `/* GENERATED by tools/derive-atmosphere.mjs — do not edit. */\n` +
    `export type AtmosEntry = { w: number; h: number; widths: number[] };\n` +
    `export const ATMOS: Record<string, AtmosEntry> = ${JSON.stringify(manifest, null, 2)};\n`
);
console.log(`atmosphere: ${written} written, ${skipped} skipped, ${(bytes / 1024 / 1024).toFixed(2)} MB out`);
