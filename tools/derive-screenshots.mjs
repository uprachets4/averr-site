/**
 * Resized WebP derivatives for every screenshot under public/work/.
 *
 * These are not new assets — each one is the same capture at a smaller
 * size, which is why locked rule 11 does not apply to them. Natural
 * aspect is preserved exactly and nothing is ever upscaled: a 1400px
 * source emits 640/960/1280/1400, not 1680.
 *
 * Outputs are committed, so the build stays a plain `vite build` with no
 * image toolchain in it. Re-run with `node tools/derive-screenshots.mjs`
 * after adding or replacing a screenshot; it is idempotent and skips any
 * derivative already newer than its source.
 *
 * It also writes src/data/screenshots.ts — the intrinsic size and the
 * available widths for each source — so <Screenshot> can build a srcset
 * and reserve the right box without every call site repeating it.
 */
import { readdir, stat, writeFile, mkdir } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import sharp from "sharp";

const ROOT = path.resolve(import.meta.dirname, "..");
const SRC_DIR = path.join(ROOT, "public/work");
const TARGET_WIDTHS = [640, 960, 1280, 1680];
const QUALITY = 78;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.(jpe?g|png)$/i.test(e.name)) out.push(p);
  }
  return out;
}

const files = (await walk(SRC_DIR)).sort();
const manifest = {};
let written = 0, skipped = 0, bytesOut = 0, bytesIn = 0;

for (const file of files) {
  const img = sharp(file);
  const { width, height } = await img.metadata();
  const srcStat = await stat(file);
  bytesIn += srcStat.size;

  // never upscale: cap the ladder at the natural width, and always
  // include the natural width itself as the top rung
  const widths = [...new Set(
    TARGET_WIDTHS.filter((w) => w < width).concat(width)
  )].sort((a, b) => a - b);

  const outDir = path.join(path.dirname(file), "w");
  if (!existsSync(outDir)) await mkdir(outDir, { recursive: true });

  for (const w of widths) {
    const base = path.basename(file).replace(/\.(jpe?g|png)$/i, "");
    const out = path.join(outDir, `${base}-${w}.webp`);
    if (existsSync(out) && (await stat(out)).mtimeMs > srcStat.mtimeMs) {
      bytesOut += (await stat(out)).size;
      skipped++;
      continue;
    }
    await sharp(file).resize({ width: w }).webp({ quality: QUALITY }).toFile(out);
    bytesOut += (await stat(out)).size;
    written++;
  }

  const key = "/" + path.relative(path.join(ROOT, "public"), file).split(path.sep).join("/");
  manifest[key] = { w: width, h: height, widths };
}

const ts = `/* GENERATED by tools/derive-screenshots.mjs — do not edit by hand. */

export type ScreenshotMeta = { w: number; h: number; widths: number[] };

/** Intrinsic size and available WebP widths, keyed by the JPEG's public path. */
export const SCREENSHOTS: Record<string, ScreenshotMeta> = ${JSON.stringify(manifest, null, 2)};
`;
await writeFile(path.join(ROOT, "src/data/screenshots.ts"), ts, "utf8");

console.log(
  `${files.length} sources · ${written} written, ${skipped} up to date\n` +
  `originals ${(bytesIn / 1024).toFixed(0)} kB · all derivatives ${(bytesOut / 1024).toFixed(0)} kB`
);
